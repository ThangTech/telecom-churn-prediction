"""Validate the Week 2 data layer and generate the canonical quality report."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.data import (  # noqa: E402
    RANDOM_STATE,
    ROW_ID_COLUMN,
    assert_split_integrity,
    basic_cleaning,
    build_train_validation_split,
    check_duplicates,
    check_missing,
    compare_columns_against_dictionary,
    compute_checksum,
    load_raw_data,
)

RAW_PATH = ROOT / "data" / "raw" / "Customer Churn.csv"
DICTIONARY_PATH = ROOT / "data" / "data_dictionary.csv"
REPORT_PATH = ROOT / "reports" / "data-quality.md"
REFERENCE_MD5 = "07311e7080c0fb5b0ce94f5977abc4d5"


def _content_keys(frame):
    import pandas as pd

    return set(pd.util.hash_pandas_object(frame.drop(columns=[ROW_ID_COLUMN]), index=False))


def run_validation() -> dict:
    raw = load_raw_data(RAW_PATH)
    schema = compare_columns_against_dictionary(raw, DICTIONARY_PATH)
    cleaned = basic_cleaning(raw)
    duplicates = check_duplicates(cleaned)
    train, val, test = build_train_validation_split(cleaned, random_state=RANDOM_STATE)
    assert_split_integrity(cleaned, train, val, test)

    repeated = build_train_validation_split(cleaned, random_state=RANDOM_STATE)
    assert [part[ROW_ID_COLUMN].tolist() for part in (train, val, test)] == [
        part[ROW_ID_COLUMN].tolist() for part in repeated
    ], "Split is not reproducible with the same random_state."

    train_keys, val_keys, test_keys = map(_content_keys, (train, val, test))
    content_overlap = {
        "train_validation": len(train_keys & val_keys),
        "train_test": len(train_keys & test_keys),
        "validation_test": len(val_keys & test_keys),
    }
    assert not any(content_overlap.values()), "Duplicate content crosses split boundaries."

    md5 = compute_checksum(RAW_PATH, "md5")
    missing = check_missing(cleaned)
    train_target = train["Churn"].value_counts().sort_index()
    train_target_table = "| Churn | count |\n|---:|---:|\n" + "\n".join(
        f"| {label} | {count} |" for label, count in train_target.items()
    )
    report = f"""# Week 2 Data Quality Report

Generated by `python scripts/validate_week2.py`. No records are removed by the default pipeline.

## Dataset and schema

- Repository CSV: `data/raw/Customer Churn.csv`
- Rows: {len(cleaned):,}
- Raw data columns: {len(cleaned.columns) - 1}
- Technical columns added at load: `{ROW_ID_COLUMN}`
- Schema matches validated data dictionary: {schema['valid']}
- Missing values: {sum(missing.values())}
- Target: `Churn` (binary 0/1)

## Duplicate content

- Unique row contents: {duplicates['n_unique_content_rows']:,}
- Excess duplicate rows: {duplicates['n_duplicate_excess_rows']:,} ({duplicates['percentage']:.2f}%)
- Duplicate groups: {duplicates['n_duplicate_groups']:,}
- Maximum group size: {duplicates['max_group_size']}
- Default decision: retain all records. Repository evidence does not establish that repeated rows are collection errors.
- Split protection: identical full-row content is assigned to one split only.

## Split

- Method: five-fold `StratifiedGroupKFold`; 3 folds train, 1 validation, 1 test.
- Intended ratio: approximately 60/20/20; group integrity can cause small deviations.
- Train: {len(train):,}
- Validation: {len(val):,}
- Test: {len(test):,}
- Random state: {RANDOM_STATE}
- Stratification: `Churn`
- `row_id` pairwise overlap: 0
- Source `row_id` coverage: {len(set(train[ROW_ID_COLUMN]) | set(val[ROW_ID_COLUMN]) | set(test[ROW_ID_COLUMN])):,}/{len(cleaned):,}
- Duplicate-content overlap: train/validation={content_overlap['train_validation']}, train/test={content_overlap['train_test']}, validation/test={content_overlap['validation_test']}
- Repeated run with same seed: identical assignment

Only train is used for EDA. Validation and test are not used to choose preprocessing, features, thresholds, or class weights. Test is reserved for final evaluation.

## Target distribution (train only)

{train_target_table}

## Outlier note

IQR flags are descriptive only. No record is removed automatically: high values can be legitimate usage behavior and require domain validation.

## Leakage note

- `Churn` is the target and is never an input feature.
- `row_id` is technical and is never an input feature.
- `Status` and `Customer Value` remain pending verification and are excluded from the default Week 3 feature set.
- Statistical association is not evidence that a feature was available before the prediction point.

## Checksum and provenance

- Exact repository artifact hashed: `data/raw/Customer Churn.csv`
- Algorithm: MD5
- Repository file MD5: `{md5}`
- Supplied source/reference CSV checksum: `{REFERENCE_MD5}`
- Result: the checksums do not match. No ZIP or alternative source artifact is present in the repository, and no conversion script explaining the difference was found. Provenance verification remains pending; the two hashes are not treated as the same artifact.
"""
    REPORT_PATH.write_text(report, encoding="utf-8")
    return {
        "rows": len(cleaned),
        "duplicates": duplicates,
        "split_sizes": (len(train), len(val), len(test)),
        "md5": md5,
        "schema_valid": schema["valid"],
        "content_overlap": content_overlap,
    }


if __name__ == "__main__":
    result = run_validation()
    print(result)
    print(f"Wrote {REPORT_PATH.relative_to(ROOT)}")
